// M_ステータスの取得用ヘルパー関数
function getStatusesFor(funcName, screenName) {
    if (!mockMasterData["M_ステータス"]) return [];
    
    return mockMasterData["M_ステータス"]
        .filter(s => s["使用FLG"] === 1 && s["対象機能"] === funcName && s["画面名称"] === screenName)
        .sort((a, b) => a["表示順"] - b["表示順"]);
}

